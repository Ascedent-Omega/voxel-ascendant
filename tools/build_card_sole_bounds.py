"""Precompute opaque shoe-support edges for digest-verified human cards."""
from pathlib import Path
import hashlib
import re
from PIL import Image

root = Path(__file__).resolve().parents[1] / 'integrated/ascendant_pokemon_overworld'
entries = dict(re.findall(r'\["([a-f0-9]{64})"\]="([a-f0-9]{64})"',
                         (root / 'production/card-file-digests.lua').read_text()))
soles = {}
for path in sorted((root / 'assets/characters').rglob('*.png')):
    key = entries.get(hashlib.sha256(path.read_bytes()).hexdigest())
    if not key or key in soles:
        continue
    with Image.open(path) as image:
        rgba = image.convert('RGBA')
        assert hashlib.sha256(rgba.tobytes()).hexdigest() == key, path
        w, h = rgba.size
        alpha = rgba.getchannel('A').point(lambda a: 255 if a > 127 else 0)
        edges = []
        for row in range(4):
            for col in range(3):
                box = alpha.crop((col*w//3, row*h//4, (col+1)*w//3, (row+1)*h//4)).getbbox()
                assert box, path
                edges.append(row*h//4 + box[3])
        soles[key] = edges
out = ['-- Opaque sole edges by verified RGBA8 digest; generated by tools/build_card_sole_bounds.py.', 'return {']
for key, edges in sorted(soles.items()):
    out.append('["' + key + '"]={' + ','.join(map(str, edges)) + '},')
out.append('}')
(root / 'production/card-sole-bounds.lua').write_text('\n'.join(out) + '\n')
print('Verified opaque sole edges:', len(soles), 'atlases')
